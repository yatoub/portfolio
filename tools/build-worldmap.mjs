#!/usr/bin/env node
/* One-off generator for tail/map.js: a dot-matrix world map and one position per country.
   Not run by CI: the output is committed. Re-run only to change the grid.

   Source data is Natural Earth (public domain, naturalearthdata.com):
     ne_110m_land.geojson              coastlines, rasterised into the grid
     ne_50m_admin_0_countries.geojson  one label point per country (the 50m set has the small ones)

   node tools/build-worldmap.mjs <land.geojson> <countries.geojson> */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const [landPath, countriesPath] = process.argv.slice(2);
if (!landPath || !countriesPath) {
    console.error('usage: node tools/build-worldmap.mjs <land.geojson> <countries.geojson>');
    process.exit(1);
}

// Equirectangular grid of square cells. Antarctica and the high Arctic are left out: nothing is plotted there.
const CELL = 3;                 // degrees per cell
const LON_LEFT = -180;
const LAT_TOP = 84;
const COLS = 360 / CELL;
const ROWS = Math.ceil((LAT_TOP + 57) / CELL);

const rings = JSON.parse(readFileSync(landPath, 'utf8')).features.flatMap((f) => {
    const g = f.geometry;
    return g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
});

function inRing(lon, lat, ring) {
    let inside = false;
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
        const [xi, yi] = ring[i], [xj, yj] = ring[j];
        if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
    }
    return inside;
}
// Outer ring minus holes
const onLand = (lon, lat) => rings.some(([outer, ...holes]) => inRing(lon, lat, outer) && !holes.some(h => inRing(lon, lat, h)));

// A cell is land when at least two of four sample points are: coasts keep their shape without speckle
const land = [];
for (let row = 0; row < ROWS; row++) {
    let bits = '';
    for (let col = 0; col < COLS; col++) {
        let hits = 0;
        for (const [dx, dy] of [[0.25, 0.25], [0.75, 0.25], [0.25, 0.75], [0.75, 0.75]]) {
            if (onLand(LON_LEFT + (col + dx) * CELL, LAT_TOP - (row + dy) * CELL)) hits++;
        }
        bits += hits >= 2 ? '1' : '0';
    }
    // 4 bits per hex digit, left to right
    land.push(bits.match(/.{4}/g).map(n => parseInt(n, 2).toString(16)).join(''));
}

const countries = {};
for (const { properties: p } of JSON.parse(readFileSync(countriesPath, 'utf8')).features) {
    const cc = /^[A-Z]{2}$/.test(p.ISO_A2) ? p.ISO_A2 : p.ISO_A2_EH;
    if (!/^[A-Z]{2}$/.test(cc) || !Number.isFinite(p.LABEL_X) || !Number.isFinite(p.LABEL_Y)) continue;
    countries[cc] = [Math.round(p.LABEL_X * 10) / 10, Math.round(p.LABEL_Y * 10) / 10];
}

const sorted = Object.fromEntries(Object.entries(countries).sort(([a], [b]) => a.localeCompare(b)));
const out = `/* ═══════════════════════════════════════════
   YATOUB // TAIL — world map data
   GENERATED by tools/build-worldmap.mjs from Natural Earth
   (public domain). Do not edit by hand.
   land: one string per row, 4 cells per hex digit, west to east.
   countries: ISO 3166-1 alpha-2 → [longitude, latitude] of a label point.
   ═══════════════════════════════════════════ */

const TailMap = {
    cell: ${CELL},
    cols: ${COLS},
    rows: ${ROWS},
    lonLeft: ${LON_LEFT},
    latTop: ${LAT_TOP},
    land: [
${land.map(r => `        '${r}',`).join('\n')}
    ],
    countries: ${JSON.stringify(sorted)},
};

if (typeof module !== 'undefined') module.exports = TailMap;
`;

const dest = join(dirname(fileURLToPath(import.meta.url)), '..', 'tail', 'map.js');
writeFileSync(dest, out);
const landCells = [...land.join('')].reduce((n, h) => n + parseInt(h, 16).toString(2).replace(/0/g, '').length, 0);
console.log(`tail/map.js: ${COLS}×${ROWS} cells, ${landCells} land cells, ${Object.keys(sorted).length} countries`);
